"""Writes src/server/food-decay-data.ts: how long each food of the game takes to spoil.

    python tools/make-food-decay.py [game folder]

The game's item tables (`Libs/Tables/item/item*.xml` in `Data/Tables.pak`) give each `<Food>` a `DecayTime`: the hours of game time
it takes from fresh (condition 1) to nothing, 0 for what never spoils (dried, smoked, salted, drinks of the brewer...). Below
`FoodHealthThreshold` (0.2, `rpg_param.xml`) the game counts a food as spoiled: eating it makes one sick. The multiplayer server
keeps every item's condition itself and never lowers it, so nothing spoiled on this server; `src/server/spoilage.ts` does it with
these numbers.
"""

import re
import sys
import zipfile
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
OUT = Path(__file__).resolve().parent.parent / "src" / "server" / "food-decay-data.ts"


def main() -> None:
    tables = zipfile.ZipFile(GAME / "Data" / "Tables.pak")
    params = tables.read("Libs/Tables/rpg/rpg_param.xml").decode("utf-8", "replace")
    threshold = float(re.search(r'rpg_param_key="FoodHealthThreshold" rpg_param_value="([^"]+)"', params).group(1))
    foods = {}
    for name in sorted(tables.namelist()):
        if not re.match(r"Libs/Tables/item/item(__[a-z0-9_]+)?\.xml$", name) or "autotest" in name:
            continue
        text = tables.read(name).decode("utf-8", "replace")
        for match in re.finditer(r"<Food ([^>]*)>", text):
            row = dict(re.findall(r'(\w+)="([^"]*)"', match.group(1)))
            hours = float(row.get("DecayTime", "0") or 0)
            guid = row.get("Id", "").lower()
            if hours > 0 and re.fullmatch(r"[0-9a-f-]{36}", guid):
                foods[guid] = (row.get("Name", ""), hours)
    lines = [
        "// Generated by tools/make-food-decay.py from the game's item tables. Do not edit by hand.",
        "",
        "/** Below this condition the game counts a food as spoiled (`FoodHealthThreshold`). */",
        f"export const SPOILED_BELOW = {threshold};",
        "",
        "/** Food that spoils: class GUID -> [the game's name, hours of game time from fresh to nothing]. */",
        "export const FOOD_DECAY: Readonly<Record<string, readonly [string, number]>> = {",
    ]
    for guid, (name, hours) in sorted(foods.items(), key=lambda item: item[1][0].lower()):
        lines.append(f'    "{guid}": ["{name}", {hours:g}],')
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(foods)} foods that spoil, threshold {threshold} -> {OUT}")


if __name__ == "__main__":
    main()
