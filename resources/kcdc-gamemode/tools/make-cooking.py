"""Writes src/server/cooking-data.ts: each food of the game and what cooking, drying and smoking make of it, from the game's tables.

    python tools/make-cooking.py [game folder]

A Food row of `Libs/Tables/item/item*.xml` names what it becomes cooked in `CookedItemId` and dried in `DriedItemId` (raw meat,
fish, an apple); the smoked form has no link, it is the Food row of the same name with "Smoked" after it (`perchSmoked`). Why
it exists: the game cooks, dries and smokes on the player's own machine, and the multiplayer mod keeps every inventory on the
server, which hears nothing of it; so `/cozinhar` (`src/server/cooking.ts`) does the swap instead.
"""

import re
import sys
import zipfile
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
OUT = Path(__file__).resolve().parent.parent / "src" / "server" / "cooking-data.ts"
TABLES = ("Libs/Tables/item/item.xml", "Libs/Tables/item/item__dlc.xml")


def main() -> None:
    tables = zipfile.ZipFile(GAME / "Data" / "Tables.pak")
    foods = {}
    for name in TABLES:
        text = tables.read(name).decode("utf-8", "replace")
        for match in re.finditer(r"<Food\b([^>]*)>", text):
            row = dict(re.findall(r'(\w+)="([^"]*)"', match.group(1)))
            foods[row["Id"]] = row
    by_name = {row["Name"]: row for row in foods.values()}
    maps = {
        "COOKED": [(r["Name"], r["Id"], r["CookedItemId"]) for r in foods.values() if r.get("CookedItemId") and r["CookedItemId"] != r["Id"]],
        "DRIED": [(r["Name"], r["Id"], r["DriedItemId"]) for r in foods.values() if r.get("DriedItemId") and r["DriedItemId"] != r["Id"]],
        "SMOKED": [(r["Name"], r["Id"], by_name[r["Name"] + "Smoked"]["Id"]) for r in foods.values() if r["Name"] + "Smoked" in by_name],
    }
    labels = {"COOKED": "cooked", "DRIED": "dried", "SMOKED": "smoked"}
    # The raw meats and fish are the ones the inventory's "Usar" is taken over for: the others (fruit, vegetables, eggs,
    # cheese, mushrooms) are eaten from the inventory, and a taken-over action would keep them from being eaten.
    processed = {raw for rows in maps.values() for _, raw, _ in rows}
    meats = sorted((r["Name"], r["Id"]) for r in foods.values() if r["Id"] in processed and r.get("SubType") == "6" and r.get("Type") != "9")
    lines = ["// Generated by tools/make-cooking.py from the game's item tables. Do not edit by hand.", ""]
    for key, rows in maps.items():
        lines += [f"/** Each food's class GUID, and the class GUID of what it becomes {labels[key]}. */", f"export const {key}: Readonly<Record<string, string>> = {{"]
        lines += [f'    "{raw}": "{made}", // {name}' for name, raw, made in sorted(rows)]
        lines += ["};", ""]
    lines += ["/** The raw meats and fish: what the inventory's \"Usar\" is taken over for, at a fire, a rack or a smokehouse. */", "export const MEATS: readonly string[] = ["]
    lines += [f'    "{guid}", // {name}' for name, guid in meats]
    lines += ["];", ""]
    OUT.write_bytes("\n".join(lines).encode("utf-8"))
    print(f"{OUT.name}: " + ", ".join(f"{len(rows)} {labels[key]}" for key, rows in maps.items()) + f"; {len(meats)} meats: " + ", ".join(n for n, _ in meats))


main()
