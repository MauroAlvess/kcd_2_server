"""Writes src/server/drink-data.ts: which items of the game quench thirst, and with what.

    python tools/make-drinks.py [game folder]

The game has no thirst of its own; this server has one (`src/server/thirst.ts`). What quenches it is what the game's item tables
file as a drink: a `<Food>` of type 3 ("drink" in `food_type.xml`), whose subtype says which -- 3 wine, 7 beer, 8 liquor, 11 water,
none for the rest (mead and the like) -- and the milk of the dairy type. A quest item is left out.
"""

import re
import sys
import zipfile
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
OUT = Path(__file__).resolve().parent.parent / "src" / "server" / "drink-data.ts"

DRINK_TYPE = "3"
DAIRY_TYPE = "9"
SUBTYPES = {"3": "wine", "7": "beer", "8": "liquor", "11": "water"}


def main() -> None:
    tables = zipfile.ZipFile(GAME / "Data" / "Tables.pak")
    drinks: dict[str, tuple[str, str]] = {}
    for name in sorted(tables.namelist()):
        if not re.match(r"Libs/Tables/item/item(__[a-z0-9_]+)?\.xml$", name) or "autotest" in name:
            continue
        text = tables.read(name).decode("utf-8", "replace")
        for match in re.finditer(r"<Food ([^>]*)>", text):
            row = dict(re.findall(r'(\w+)="([^"]*)"', match.group(1)))
            guid = row.get("Id", "").lower()
            if not re.fullmatch(r"[0-9a-f-]{36}", guid) or row.get("IsQuestItem") == "true":
                continue
            kind = ""
            if row.get("Type") == DRINK_TYPE:
                kind = SUBTYPES.get(row.get("SubType", ""), "drink")
            elif row.get("Type") == DAIRY_TYPE and "milk" in row.get("Name", "").lower():
                kind = "milk"
            if kind != "":
                drinks[guid] = (row.get("Name", ""), kind)
    lines = [
        "// Generated by tools/make-drinks.py from the game's item tables. Do not edit by hand.",
        "",
        "/** What a drink is, for how much it quenches (`thirst.ts`). */",
        'export type DrinkKind = "water" | "milk" | "beer" | "wine" | "liquor" | "drink";',
        "",
        "/** The items that quench thirst: class GUID -> [the game's name, what kind of drink it is]. */",
        "export const DRINKS: Readonly<Record<string, readonly [string, DrinkKind]>> = {",
    ]
    for guid, (name, kind) in sorted(drinks.items(), key=lambda item: (item[1][1], item[1][0].lower())):
        lines.append(f'    "{guid}": ["{name}", "{kind}"],')
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    kinds: dict[str, int] = {}
    for _, kind in drinks.values():
        kinds[kind] = kinds.get(kind, 0) + 1
    print(f"{len(drinks)} drinks {kinds} -> {OUT}")


if __name__ == "__main__":
    main()
