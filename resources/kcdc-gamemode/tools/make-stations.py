"""Writes src/server/stations-data.ts: where the level's food-processing places are (fireplaces, dryers and smokehouses).

    python tools/make-stations.py [game folder]

The level places each place a food is cooked, dried or smoked at as a `FoodProcessingTrigger` entity (`TriggerFireplace` and
`trigger_pan` for the fires, `butcher_dryer` and `butcher_smokeHouse` for the butchers' racks and smokehouses), and the
layers of `level.pak` hold its position. Why it exists: the game cooks, dries and smokes on the player's own machine and
the multiplayer mod never hears of it, so `src/server/cooking.ts` does it for a player who stands at one of these places.
"""

import re
import struct
import sys
import zipfile
import zlib
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
OUT = Path(__file__).resolve().parent.parent / "src" / "server" / "stations-data.ts"


def read_member(f, zi) -> bytes:
    """The pak's names carry backslashes that Python's zipfile refuses, so the entry is read by hand."""
    f.seek(zi.header_offset)
    header = f.read(30)
    method = struct.unpack("<H", header[8:10])[0]
    size = struct.unpack("<I", header[18:22])[0]
    name_len, extra_len = struct.unpack("<HH", header[26:30])
    f.seek(name_len + extra_len, 1)
    raw = f.read(size if size else zi.compress_size)
    return raw if method == 0 else zlib.decompress(raw, -15)


def kind_of(name: str) -> str:
    if "butcher_dryer" in name:
        return "secador"
    if "butcher_smokeHouse" in name:
        return "defumador"
    return "fogo"


def main() -> None:
    pak = GAME / "Data" / "Levels" / "kutnohorsko" / "level.pak"
    found = []
    with zipfile.ZipFile(pak) as z, open(pak, "rb") as f:
        for zi in z.infolist():
            if not (zi.filename.startswith("layers/") and zi.filename.endswith(".xml")):
                continue
            text = read_member(f, zi).decode("utf-8", "replace")
            for match in re.finditer(r"<Entity\b([^>]*)>", text):
                row = dict(re.findall(r'([\w.]+)="([^"]*)"', match.group(1)))
                if row.get("EntityClass") == "FoodProcessingTrigger":
                    x, y, z_ = (float(v) for v in row["Pos"].split(","))
                    found.append((kind_of(row.get("Name", "")), round(x, 1), round(y, 1), round(z_, 1)))
    found.sort()
    lines = [
        "// Generated by tools/make-stations.py from the level's layers. Do not edit by hand.",
        "",
        "export type StationKind = \"fogo\" | \"secador\" | \"defumador\";",
        "",
        "/** Each place the level cooks (a fire), dries (a butcher's rack) or smokes (a smokehouse) food at: kind, x, y, z. */",
        "export const STATIONS: ReadonlyArray<readonly [StationKind, number, number, number]> = [",
    ]
    lines += [f'    ["{kind}", {x}, {y}, {z}],' for kind, x, y, z in found]
    lines += ["];", ""]
    OUT.write_bytes("\n".join(lines).encode("utf-8"))
    counts = {k: sum(1 for s in found if s[0] == k) for k in ("fogo", "secador", "defumador")}
    print(f"{OUT.name}: {counts}")


main()
