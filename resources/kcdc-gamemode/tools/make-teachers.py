"""Writes src/server/teachers-data.ts: the game's skill teachers that stand in this level, where they stand, what each teaches.

    python tools/make-teachers.py [game folder]

`Libs/Tables/rpg/skill_teacher.xml` lists the souls that teach (up to which level, for each skill) and
`skill_lesson_level.xml` what a lesson up to a level costs. A teacher is an NPC of the level: the layers of `level.pak`
and its `objects_mission0.xml` hold each one's position under the soul's name, and the Portuguese localization its name
(`<skald_character_name>_uiName` of the soul in `soul__*.xml`). The teachers of the other levels (Trosky, the monastery
of Sedlec) are left out: this server runs this level only. Why it exists: the game's trainers are only in the world when
the game's own population puts them there, which the framework does not do (`src/server/teachers.ts`).
"""

import json
import re
import struct
import sys
import zipfile
import zlib
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
OUT = Path(__file__).resolve().parent.parent / "src" / "server" / "teachers-data.ts"
NPC_CLASSES = ("NPC", "NPC_Female")


def attrs(text: str) -> dict:
    return dict(re.findall(r'([\w.]+)="([^"]*)"', text))


def read_member(f, zi) -> bytes:
    """The pak's names carry backslashes that Python's zipfile refuses, so the entry is read by hand."""
    f.seek(zi.header_offset)
    header = f.read(30)
    method = struct.unpack("<H", header[8:10])[0]
    size = struct.unpack("<I", header[18:22])[0]
    name_len, extra_len = struct.unpack("<HH", header[26:30])
    f.seek(name_len + extra_len, 1)
    raw = f.read(size if size else zi.compress_size)
    return raw if method == 0 else zlib.decompress(raw, -15)


def teachers_of(tables: zipfile.ZipFile) -> list:
    text = tables.read("Libs/Tables/rpg/skill_teacher.xml").decode("utf-8", "replace")
    found = []
    for match in re.finditer(r"<SkillTeacher\b([^>]*)>(.*?)</SkillTeacher>", text, re.S):
        note = re.search(r"<!--(.*?)-->", text[match.start(): match.start() + 400])
        name = re.split(r"[\s,]", note.group(1).strip())[0] if note else ""
        lessons = [(a["Skill"], int(a["Level"])) for a in (attrs(l) for l in re.findall(r"<Lesson\b([^>]*)/?>", match.group(2)))]
        if re.match(r"k[a-z]{3}_", name) and lessons:
            found.append((name, lessons))
    return found


def places_of(pak: Path, wanted: set) -> dict:
    places = {}
    with zipfile.ZipFile(pak) as z, open(pak, "rb") as f:
        for zi in z.infolist():
            if not (zi.filename == "objects_mission0.xml" or (zi.filename.startswith("layers/") and zi.filename.endswith(".xml"))):
                continue
            text = read_member(f, zi).decode("utf-8", "replace")
            for match in re.finditer(r"<Entity\b([^>]*)>", text):
                row = attrs(match.group(1))
                if row.get("Name") in wanted and row.get("EntityClass") in NPC_CLASSES and row["Name"] not in places:
                    x, y, z_ = (float(v) for v in row["Pos"].split(","))
                    places[row["Name"]] = (row["EntityClass"] == "NPC_Female", round(x, 1), round(y, 1), round(z_, 1))
    return places


def names_of(tables: zipfile.ZipFile, game: Path, wanted: set) -> dict:
    characters = {}
    for member in tables.namelist():
        if member.startswith("Libs/Tables/rpg/soul") and member.endswith(".xml"):
            for match in re.finditer(r"<soul\b([^>]*)/>", tables.read(member).decode("utf-8", "replace")):
                row = attrs(match.group(1))
                if row.get("soul_name") in wanted and row.get("skald_character_name"):
                    characters[row["soul_name"]] = row["skald_character_name"]
    loc = zipfile.ZipFile(game / "Localization" / "Portuguese_xml.pak").read("text_ui_soul.xml").decode("utf-8", "replace")
    shown = {}
    for key, character in characters.items():
        match = re.search(r"<Row><Cell>%s_uiName</Cell><Cell>[^<]*</Cell><Cell>([^<]*)</Cell>" % re.escape(character), loc)
        if match:
            shown[key] = match.group(1).strip()
    return shown


def main() -> None:
    tables = zipfile.ZipFile(GAME / "Data" / "Tables.pak")
    teachers = teachers_of(tables)
    wanted = {name for name, _ in teachers}
    places = places_of(GAME / "Data" / "Levels" / "kutnohorsko" / "level.pak", wanted)
    names = names_of(tables, GAME, wanted)
    prices = [(int(a["Level"]), int(a["Price"])) for a in (attrs(m) for m in re.findall(r"<SkillLessonLevel\b([^>]*)/>", tables.read("Libs/Tables/rpg/skill_lesson_level.xml").decode("utf-8", "replace")))]

    lines = [
        "// Generated by tools/make-teachers.py from the game's tables and the level. Do not edit by hand.",
        "",
        "export interface TeacherData {",
        "    /** The soul's name in the game's tables. */",
        "    readonly id: string;",
        "    /** The name the Portuguese game gives them. */",
        "    readonly name: string;",
        "    readonly female: boolean;",
        "    readonly x: number;",
        "    readonly y: number;",
        "    readonly z: number;",
        "    /** What they teach: the skill, and the highest level they take a pupil to. */",
        "    readonly lessons: ReadonlyArray<readonly [string, number]>;",
        "}",
        "",
        "/** What a lesson up to each level costs, in coins as the game shows them: level, price. */",
        f"export const LESSON_PRICES: ReadonlyArray<readonly [number, number]> = {json.dumps(prices)};",
        "",
        "export const TEACHERS: readonly TeacherData[] = [",
    ]
    kept = 0
    for name, lessons in sorted(teachers, key=lambda t: t[0]):
        if name not in places:
            continue
        female, x, y, z = places[name]
        shown = names.get(name, name)
        lines.append(f'    {{ id: "{name}", name: {json.dumps(shown, ensure_ascii=False)}, female: {str(female).lower()}, x: {x}, y: {y}, z: {z}, lessons: {json.dumps([list(l) for l in lessons])} }},')
        kept += 1
    lines += ["];", ""]
    OUT.write_bytes("\n".join(lines).encode("utf-8"))
    print(f"{OUT.name}: {kept} professores de {len(teachers)} do nível; sem lugar: {sorted(wanted - set(places))}")


main()
