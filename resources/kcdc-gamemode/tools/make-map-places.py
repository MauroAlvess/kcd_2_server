"""Writes src/server/map-places-data.ts: the places the game's own map names, as the map writes them in Portuguese.

    python tools/make-map-places.py <places.lines> [game folder] [level]

`level` is `kutnohorsko` (the default: `map-places-data.ts`) or `trosecko` (`map-places-data-trosecko.ts`, 2026-11-09: the places of the Trosky level, read by the same probe).

`places.lines` is what a probe on a throwaway copy of the server prints (the `PROBE PLACE {...}` lines of every `Area.location` of the level, with the bounds of
the areas that carry it: see `mapLocations()` in `src/server/properties.ts`). The names are the game's own `location_*` texts of `text_ui_quest.xml`
(`Localization/Portuguese_xml.pak`), keyed by the English name the level gives the area, so a place reads on the panel exactly as it reads on the map
(2026-10-26: "no mapa se chama Minas em português": Grund is "Minas", the Devil's Den is "Toca do Diabo", Old Lhota is "Lhota").
"""

import json
import re
import sys
import zipfile
from pathlib import Path

LINES = Path(sys.argv[1])
GAME = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
LEVEL = sys.argv[3] if len(sys.argv) > 3 else "kutnohorsko"
SERVER = Path(__file__).resolve().parent.parent / "src" / "server"
OUT = SERVER / ("map-places-data.ts" if LEVEL == "kutnohorsko" else "map-places-data-trosecko.ts")

# What a thing is told against: a village, a town, a camp, a monastery, a stronghold. The others are parts of places (an inn, a vineyard, a graveyard,
# a hill) and are named when a spot lies inside them, not used to say where something else is. The composite outline of the camp and Opatowitz is no place.
LANDMARKS = {
    "Bohunowitz", "Bylany", "Danemark", "Devil's Den", "Grund", "Horschan", "Kuttenberg", "Maleshov", "Mesoles", "Miskowitz", "Old Kutna", "Old Lhota",
    "Opatowitz", "Pschitoky", "Raborsch", "Rabstein", "Sedletz Monastery", "Sigismund's camp", "Suchdol", "Wysoka", "Zimburg",
}
LEFT_OUT = {"Sigismund's camp and Opatowitz"}
if LEVEL == "trosecko":
    # The Trosky level (2026-11-09): the villages, the camp and the strongholds are what a thing is told against; mills, farms, ponds and a valley are parts of places.
    LANDMARKS = {"Apollonia", "Nebakov Fortress", "Nomads' Camp", "Semine", "Slatego", "Tachov", "Troskowitz", "Trosky Castle", "Zhelejov"}
    LEFT_OUT = set()
# How the name goes after "de" ("ao norte de Suchdol"): the game speaks of Grund as "as Minas" ("Você quer ir às Minas?"), and a few places carry an article of their own.
ARTICLES = {
    "Lower Semine Mill": "do", "Nebakov Fortress": "da", "Nebakov Mill": "do", "Nomads' Camp": "do", "Rocktower Pond": "do", "Schdiar Valley": "do", "Trosky Castle": "do",
    "Vidlak Pond": "da", "Zhelejov Wagoners' Inn": "da",
    "Devil's Den": "da", "Grund": "das", "Sedletz Monastery": "do", "Sigismund's camp": "do", "Wysoka Hill": "da", "Monastery Vineyard": "do",
    "Monastery Cemetery": "do", "Ossuary": "do", "Old Kutna Wagoners' Inn": "da", "Pschitoky Wagoners' Inn": "da",
}


def unescape(text: str) -> str:
    return text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", '"').replace("&apos;", "'")


def portuguese_names() -> dict:
    pak = zipfile.ZipFile(GAME / "Localization" / "Portuguese_xml.pak")
    raw = pak.read("text_ui_quest.xml")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("cp1252", "replace")
    found = {}
    for row in re.finditer(r"<Row>(.*?)</Row>", text, re.S):
        cells = re.findall(r"<Cell>(.*?)</Cell>", row.group(1), re.S)
        if len(cells) >= 3 and cells[0].startswith("location_"):
            found.setdefault(unescape(cells[1]).strip(), unescape(cells[2]).strip())
    return found


def main() -> None:
    names = portuguese_names()
    places = []
    for line in LINES.read_text(encoding="utf-8").splitlines():
        if line.startswith("PROBE PLACE "):
            places.append(json.loads(line[len("PROBE PLACE "):]))
    rows = []
    for place in sorted(places, key=lambda one: one["name"]):
        english = place["name"]
        if english in LEFT_OUT:
            continue
        if english not in names:
            raise SystemExit(f"no Portuguese name for {english!r}")
        rows.append((english, names[english], place))
    out = ["// Generated by tools/make-map-places.py from the level's map locations and the game's Portuguese texts. Do not edit by hand.", ""]
    if LEVEL != "kutnohorsko":
        out += [f"// The level: {LEVEL}.", 'import type { MapPlaceData } from "./map-places-data.js";', ""]
    if LEVEL == "kutnohorsko":
        out.append("/** A place of the game's map: the name the level gives it (English), the name on the map (Portuguese) and its outline in the level's coordinates (+Y is north). */")
        out.append("export interface MapPlaceData {")
        out.append("    readonly en: string;")
        out.append("    readonly name: string;")
        out.append("    /** The name after \"de\" with its article: \"de Suchdol\", \"da Toca do Diabo\", \"das Minas\". */")
        out.append("    readonly of: string;")
        out.append("    readonly minX: number;")
        out.append("    readonly maxX: number;")
        out.append("    readonly minY: number;")
        out.append("    readonly maxY: number;")
        out.append("    /** A village, town, camp or stronghold: what a thing is told against. The others are parts of a place (an inn, a vineyard, a hill). */")
        out.append("    readonly landmark: boolean;")
        out.append("}")
        out.append("")
    out.append(f"export const {'MAP_PLACE_DATA' if LEVEL == 'kutnohorsko' else 'MAP_PLACE_DATA_TROSECKO'}: readonly MapPlaceData[] = [")
    for english, portuguese, place in rows:
        box = [round(place["minX"]), round(place["maxX"]), round(place["minY"]), round(place["maxY"])]
        out.append(
            f'    {{ en: {json.dumps(english, ensure_ascii=False)}, name: {json.dumps(portuguese, ensure_ascii=False)}, of: {json.dumps(ARTICLES.get(english, "de") + " " + portuguese, ensure_ascii=False)}, minX: {box[0]}, maxX: {box[1]}, minY: {box[2]}, maxY: {box[3]}, landmark: {"true" if english in LANDMARKS else "false"} }},'
        )
    out.append("];")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} places -> {OUT}")


main()
