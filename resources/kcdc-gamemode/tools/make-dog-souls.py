"""Writes src/server/dog-souls.ts: the souls of the game's village dogs, which a supporter's dog is drawn from, and the GUIDs of the souls the village
dogs of this server wear.

    python tools/make-dog-souls.py [game folder]

A dog the server spawns for a player (`Dog.spawn`) takes its looks from the soul it is spawned against; spawned without one it is the game's
generic dog, and every supporter's would be the same dog. The game files a soul for each dog of its villages (`ksuc_dog_1`, `kvys_dog_3`,
`ttkc_dog_5`: the village's letters, `dog`, a number) in the soul tables (`soul__*.xml`), with the class `dog` (31) and the faction of the
village's own folk. Left out: wild dogs and wolves (they hunt), the dogs of bandit camps and the dead, and the quest dogs (named for the quest
and not for a village: `hladAZmar_strayDog`, `korenarka_dog`), and the souls the village dogs of this server wear (`DOG_POOLS` in
`village-pets.ts`: Suchdol, Malešov, Wysoka, Raborsch), so that no soul is worn by two dogs of ours at once. Run it again if that list changes.

The village dogs' own souls (and the generic dog, `animal_dog`) are written apart, as name -> GUID (`VILLAGE_DOG_GUIDS`): the engine spawns a body on the
clients only from a GUID, and the client log said "Could not spawn NPC ... soul must be a plain 8-4-4-4-12 GUID" for every one of them (2026-10-26) while the
server believed it had made them.
"""

import re
import sys
import zipfile
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Program Files (x86)\Steam\steamapps\common\KingdomComeDeliverance2")
OUT = Path(__file__).resolve().parent.parent / "src" / "server" / "dog-souls.ts"

VILLAGE_DOG = re.compile(r"[kt][a-z]{2,3}_dog_?[0-9]+")
DOG_CLASS = "31"
NOT_FOLK = re.compile(r"wild|enem|dead", re.I)


def main() -> None:
    tables = zipfile.ZipFile(GAME / "Data" / "Tables.pak")
    found: dict[str, str] = {}
    for name in sorted(tables.namelist()):
        if not re.match(r"Libs/Tables/rpg/soul__[A-Za-z0-9_]+\.xml$", name):
            continue
        text = tables.read(name).decode("utf-8", "replace")
        for match in re.finditer(r"<soul\s([^>]*?)/?>", text):
            row = dict(re.findall(r'(\w+)="([^"]*)"', match.group(1)))
            soul = row.get("soul_name", "")
            guid = row.get("soul_id", "").lower()
            if not re.fullmatch(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", guid):
                continue
            if not VILLAGE_DOG.fullmatch(soul) or row.get("soul_class_id") != DOG_CLASS or NOT_FOLK.search(row.get("factionName", "")):
                continue
            found[soul] = guid
    lines = [
        "// Generated by tools/make-dog-souls.py from the game's soul tables. Do not edit by hand.",
        "",
        "/** The village dogs' souls a supporter's dog is drawn from (`supporters.ts`): [the soul's name, its GUID]. A soul decides how its dog looks. */",
        "export const DOG_SOULS: ReadonlyArray<readonly [name: string, guid: string]> = [",
    ]
    for soul in sorted(found, key=lambda s: (re.sub(r"[0-9]+$", "", s), int(re.search(r"([0-9]+)$", s).group(1)))):
        lines.append(f'    ["{soul}", "{found[soul]}"],')
    lines.append("];")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(found)} dog souls -> {OUT}")


if __name__ == "__main__":
    main()
